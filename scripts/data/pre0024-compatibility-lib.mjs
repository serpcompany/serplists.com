import { readFileSync } from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { parseStrictJson } from './strict-json-lib.mjs';

// Call on ALL raw rows before sampling, identity mapping or pre-mutation
// attestation, only when 0024 is pending. No row identifiers are needed.
// Success returns undefined; failures contain only fixed diagnostic codes.
export function assertPre0024Compatibility({ repoRoot, templates, runs }) {
  const database = new DatabaseSync(':memory:');
  try {
    database.exec('CREATE TABLE templates(items TEXT, version INTEGER DEFAULT 1); CREATE TABLE checklist_runs(items TEXT, template_id TEXT);');
    const counts = value => {
      const result = new Map();
      const add = (entry, namespace) => {
        if (typeof entry?.id !== 'string') return;
        const key = JSON.stringify([namespace, entry.id]);
        result.set(key, (result.get(key) ?? 0) + 1);
      };
      const array = entry => Array.isArray(entry) ? entry : [];
      const parsed = parseStrictJson(value);
      // Match legacySectionsSchema: sections, items and subitems have
      // separate global namespaces. Content IDs are local to each item and
      // never generated by 0024; arbitrary passthrough extension IDs are
      // opaque. Neither belongs in these collision counts.
      // Flat legacy rows contain items; 0024 wraps them in a section first.
      const sections = parsed.length && !Object.hasOwn(parsed[0] ?? {}, 'items') ? [{ items: parsed }] : parsed;
      for (const section of sections) {
        add(section, 'section');
        for (const item of array(section?.items)) {
          add(item, 'item');
          for (const child of array(item?.subItems)) add(child, 'subitem');
          for (const content of array(item?.contents)) for (const child of array(content?.subItems)) add(child, 'subitem');
        }
      }
      return result;
    };
    const before = {};
    for (const [table, rows] of [['templates', templates], ['checklist_runs', runs]]) {
      if (!Array.isArray(rows)) throw new Error();
      before[table] = rows.map(row => {
        if (typeof row.items !== 'string' || !Array.isArray(parseStrictJson(row.items))) throw new Error();
        database.prepare(`INSERT INTO ${table}(items) VALUES (?)`).run(row.items);
        return counts(row.items);
      });
    }
    // Execute the immutable authority, rather than maintaining a second copy
    // of its path/backfill rules. Only disposable in-memory rows are mutated.
    database.exec(readFileSync(path.join(repoRoot, 'db/migrations/0024_safe_template_evolution.sql'), 'utf8'));
    for (const table of ['templates', 'checklist_runs']) {
      for (const [index, row] of database.prepare(`SELECT items FROM ${table} ORDER BY rowid`).all().entries()) {
        for (const [id, count] of counts(row.items)) {
          if (count > 1 && count > (before[table][index].get(id) ?? 0)) {
            throw new Error('Production-shaped source is incompatible with immutable 0024 (GENERATED_ID_COLLISION).');
          }
        }
      }
    }
  } catch (error) {
    if (error?.message === 'Production-shaped source is incompatible with immutable 0024 (GENERATED_ID_COLLISION).') throw error;
    throw new Error('Production-shaped source compatibility with immutable 0024 could not be verified (PRE0024_COMPATIBILITY).');
  } finally { database.close(); }
}
